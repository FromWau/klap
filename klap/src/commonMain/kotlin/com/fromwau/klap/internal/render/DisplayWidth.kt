package com.fromwau.klap.internal.render

/**
 * The terminal columns [text] takes: an East Asian wide or full-width character (日, Ａ, most emoji) two, a
 * combining mark or a zero-width format character (U+0301, U+200B) none, every other character one.
 */
internal fun displayWidth(text: CharSequence): Int {
    var width = 0
    var i = 0
    while (i < text.length) {
        val high = text[i]
        val low = text.getOrNull(i + 1)
        if (high.isHighSurrogate() && low != null && low.isLowSurrogate()) {
            width += supplementaryWidth(0x10000 + ((high.code - 0xD800) shl 10) + (low.code - 0xDC00))
            i += 2
        } else {
            width += bmpWidth(high)
            i += 1
        }
    }
    return width
}

/** [text] padded with spaces to [width] columns, as [String.padEnd] pads to a length. */
internal fun padToWidth(text: String, width: Int): String =
    text + " ".repeat((width - displayWidth(text)).coerceAtLeast(0))

private val ZERO_WIDTH = setOf(CharCategory.NON_SPACING_MARK, CharCategory.ENCLOSING_MARK, CharCategory.FORMAT)

private fun bmpWidth(char: Char): Int = when {
    char.category in ZERO_WIDTH -> 0
    WIDE.containsCodePoint(char.code) -> 2
    else -> 1
}

private fun supplementaryWidth(codePoint: Int): Int = when {
    SUPPLEMENTARY_ZERO_WIDTH.containsCodePoint(codePoint) -> 0
    WIDE.containsCodePoint(codePoint) -> 2
    else -> 1
}

/** Whether [codePoint] falls in one of these sorted, inclusive `first, last` pairs. */
private fun IntArray.containsCodePoint(codePoint: Int): Boolean {
    var lo = 0
    var hi = size / 2 - 1
    while (lo <= hi) {
        val mid = (lo + hi) ushr 1
        when {
            codePoint < this[2 * mid] -> hi = mid - 1
            codePoint > this[2 * mid + 1] -> lo = mid + 1
            else -> return true
        }
    }
    return false
}

